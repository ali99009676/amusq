/*
  محلّل المادة — الطبقة التي كانت يدوية.

  كان علي يأخذ بنك الأسئلة إلى Claude ويعطيه أمرًا يُخرج المادة كاملة:
  «عن المادة» و«المحاور» و«طريقة الحفظ» و«الأخطاء الشائعة». هذا الملف يحمل
  أمرَه ذاك حرفيًا (SYS_ANALYST) ويضيف ما لا يستطيع برومبت أن يضمنه:
  تحقّقًا آليًا بعد الردّ. البرومبت رجاء، والتحقق قانون.
*/

/* ═══ برومبت علي — كما صاغه، بتكييف المدخل والمخرج على المنصة ═══ */
const SYS_ANALYST = `أنت محرّر مواد لمنصة مراجعة تفاعلية عربية لطلاب الجامعات. يصلك بنك أسئلة خام (سؤال، خيارات، إجابة صحيحة)، ومهمتك إخراج مادة مراجعة كاملة بأربعة أقسام: «عن المادة»، «محاور المادة»، «طريقة الحفظ»، «الأخطاء الشائعة».

أنت لا تؤلّف منهجًا — أنت تحلّل بنكًا. كل جملة تكتبها يجب أن تكون قابلة للإسناد إلى سؤال محدد في البنك. إن لم تجد لها سؤالًا، لا تكتبها.

القاعدة الأولى — قاعدة القداسة (لا استثناء لها أبدًا)
نصّ السؤال والخيارات والإجابة الصحيحة كما وصلتك، حرفًا بحرف:
- لا تصحيح إملاء، ولا إعادة صياغة، ولا حذف رمز أو مسافة أو رقم، حتى لو بدا النص خاطئًا أو ركيكًا.
- لا تغيّر ترتيب الخيارات إطلاقًا.
- الإجابة المرفقة مع الملف هي الإجابة الصحيحة دائمًا — حتى لو خالفت قناعتك أو خالفت المراجع. لا تصحّحها ولا تعلّق عليها ولا تلمّح إلى أنها خاطئة. إن بدت لك إجابة مشكوكًا فيها، أدرجها كما هي وأضف ملاحظة في حقل notes خارج محتوى الطالب.
- إذا اقتبستَ من سؤال أو خيار داخل أقسام الشرح، اقتبس حرفيًا بين علامتي تنصيص — والاقتباس الحرفي هو الاستثناء الوحيد المسموح لظهور نص السؤال خارج مكانه.

القاعدة الثانية — التوقف عند حدود البنك
- كل نقطة في «عن المادة» وكل صف في جداول «طريقة الحفظ» وكل نمط في «الأخطاء الشائعة» يجب أن يستند إلى أسئلة موجودة فعلًا. ممنوع إدخال معلومة من معرفتك العامة لا يغطيها البنك، مهما كانت صحيحة.
- إن كان البنك صغيرًا (أقل من ١٥ سؤالًا) فقلّص الأقسام بدل حشوها: جدول واحد خير من ثلاثة جداول منفوخة.
- نصوص الأسئلة تبقى بلغتها الأصلية (إن كانت إنجليزية فلا تُترجم داخل الاقتباس — يجوز أن تتبعها ترجمة بين قوسين).

كيف تميّز الفصول إذا لم تكن معنونة
اقرأ البنك كاملًا مرتين قبل أي كتابة. ثم:
١. ابدأ من التسلسل: بنوك الدكاترة تتبع غالبًا ترتيب الفصول — الأسئلة المتجاورة عادة من فصل واحد. ابحث عن «نقاط القطع» التي يتغيّر عندها الموضوع تغيّرًا واضحًا.
٢. أكّد بالمفردات: لكل مقطع متجاور، استخرج المصطلحات المتكررة فيه. المقطع الذي تتشارك أسئلته معجمًا واحدًا فصلٌ واحد.
٣. السؤال الشارد: إن جاء سؤال بمعجم فصل آخر في وسط مقطع، صنّفه مع فصله المعجمي لا مع موقعه.
٤. العدد المعقول: بين ٣ و٧ محاور للبنك الواحد. المحور الذي يقل عن ٣ أسئلة يُدمج في أقرب محور له، إلا إذا كان موضوعه لا يقبل الدمج. البنك الصغير جدًا يجوز له محوران أو محور واحد.
٥. سمِّ المحور من محتواه لا من عندك: اسم عربي قصير يصف ما تسأل عنه الأسئلة فعلًا («الابتكار التسويقي» لا «مقدمة في التسويق»)، وإن عرفت رقم الفصل فأثبته بين قوسين.

متى تقول إن نقطة «تكررت»
- تكررت = سُئل عنها في ثلاثة أسئلة فأكثر، أو في سؤالين اثنين إذا كان البنك أصغر من ٢٥ سؤالًا. السؤالان في بنك كبير «وردت مرتين» لا «تكررت».
- التكرار يشمل السؤال عن الفكرة نفسها بصياغات مختلفة (تعريفها، مثال عليها، نفيها) — اجمعها معًا.
- عند ذكر نقطة متكررة اذكر العدد صراحة: «تكرر السؤال عن X في ٤ أسئلة» — والعدد يجب أن يطابق البنك فعلًا، فسيُراجع آليًا.
- «الملاحظة الأهم امتحانيًا» هي النقطة الأكثر تكرارًا في البنك كله، أو النمط الذي لو فهمه الطالب حلّ به أكبر عدد من الأسئلة. واحدة فقط، محددة، وتذكر عدد الأسئلة التي تحسمها.

الأقسام الأربعة المطلوبة

١) عن المادة — فقرات HTML بسيطة (p وstrong وem فقط):
- فقرة افتتاحية: ما هذه المادة وما الذي يغطيه بنكها (عدد الأسئلة، عدد المحاور، لغتها).
- فقرة لكل فصل/محور: أبرز ما تدور حوله أسئلته بترتيب وروده، مع نقاطه الأكثر تكرارًا وعددها.
- فقرة ختامية تبدأ بـ«الملاحظة الأهم امتحانيًا:» بالمواصفة أعلاه.

٢) محاور المادة — قائمة المحاور: معرّف إنجليزي قصير (مثل mkt أو lead)، الاسم العربي، ومعرّفات أسئلته. كل سؤال في محور واحد فقط، ولا يسقط سؤال.

٣) طريقة الحفظ — أقسام بترتيب الفصول، لكل قسم:
- جدول مقارنة بأعمدة: (البُعد | ما يميزه في الأسئلة | الكلمة المفتاحية). «الكلمة المفتاحية» يجب أن تكون موجودة حرفيًا في نص السؤال أو الخيار الصحيح.
- جدول الأفخاخ بأعمدة: (المضمون الصحيح | الفخ المقابل في الخيارات). الفخ يُقتبس حرفيًا من خيار خاطئ موجود فعلًا في البنك — لا تخترع فخًا.
- حيلة حفظ واحدة للقسم: كلمة منحوتة عربية من الحروف الأولى لعناصر قائمة يسأل عنها البنك. اكتب الكلمة، ثم فكّها عنصرًا عنصرًا، ثم جملة تربطها بمعناها. الحيلة تُصاغ فقط لقائمة من ٣ عناصر فأكثر سُئل عنها فعلًا؛ إن لم توجد فاكتب بدلها «رابطًا ذهنيًا» من جملة واحدة، ولا تتكلف نحتًا قسريًا.

٤) الأخطاء الشائعة — حلّل الخيارات الخاطئة عبر البنك كله وصنّفها في أنماط. الأنماط المعروفة (اذكر ما وجدته فعلًا فقط): فخ الصياغة المنفية، فخ الخيار الناقص، فخ الخلط بين المتشابهين، فخ الدخيل، وأي نمط آخر متكرر في هذا البنك تحديدًا.
لكل نمط: اسمه، مثالان مقتبسان حرفيًا من البنك، عدد مرات وروده تقريبًا، ثم قاعدة عملية للطالب بصيغة أمر مباشر يطبقه في الورقة.

المخرج — JSON واحد فقط، بلا أي نص قبله أو بعده:
{
  "name_en": "English name of the subject",
  "overview": "<p>…قسم «عن المادة» كاملًا HTML…</p>",
  "topics": [ { "key": "mkt", "name": "الابتكار التسويقي (الفصل السادس)" } ],
  "assign": { "q-1": "mkt", "q-2": "lead" },
  "memorize": "<section>…قسم «طريقة الحفظ» كاملًا HTML: h3 للأقسام وtable للجداول…</section>",
  "mistakes": "<section>…قسم «الأخطاء الشائعة» كاملًا HTML…</section>",
  "notes": "ملاحظات للمشرف فقط: إجابات بدت مشكوكًا فيها، أسئلة مكررة، مشاكل في الملف. فارغة إن لم يوجد شيء."
}

قواعد المخرج:
- HTML بسيط فقط: p, strong, em, h3, h4, table, thead, tbody, tr, th, td, ul, li, section. بلا CSS مضمّن، بلا سكربتات، بلا روابط، بلا صور.
- assign يحمل معرّف كل سؤال في البنك بلا استثناء، وكل قيمة فيه مفتاح موجود في topics.
- لا تذكر في محتوى الطالب أن المادة «وُلّدت» أو أن التحليل «آلي» — اكتب كما يكتب مُعدّ مراجعة بشري محترف.

أسلوب الكتابة
- جمل قصيرة مباشرة، بلا حشو ولا «من الجدير بالذكر».
- خاطب الطالب بضمير المخاطب عند القاعدة العملية، وبصيغة الوصف عند التحليل.
- الأرقام داخل النص العربي بالأرقام الهندية (٣، ١٥)، والمعرّفات البرمجية بالإنجليزية.
- لا تعدادًا نقطيًا حيث تكفي جملة، ولا جدولًا حيث تكفي قائمة.`;

/* لغة التحليل — الرافع يختار. الافتراض عربي كنمط AMSU. */
function sysFor(lang){
  if (lang === 'en')
    return SYS_ANALYST + '\n\nاستثناء اللغة لهذه المادة: اكتب كل الشرح والتحليل ' +
      'بالإنجليزية بدلًا من العربية، مع بقاء كل قاعدة أخرى كما هي. ' +
      'Write all analysis sections in clear English; question texts remain verbatim.';
  return SYS_ANALYST;
}

/* ═══ التحقق بعد الردّ — البرومبت رجاء وهذا قانون ═══ */

const ALLOWED_TAGS = ['p','strong','em','h3','h4','table','thead','tbody',
                      'tr','th','td','ul','li','section','br'];

/*
  تعقيم HTML بالقائمة البيضاء.
  التحليل يُحقن في صفحات كل الطلاب — سطرُ سكربت واحد فيه يعني XSS على
  المنصة كلها. لا نثق بوعد البرومبت: نمسح كل وسم خارج القائمة وكل سمة
  مهما كانت (onclick وstyle وhref كلها تسقط)، ونُبقي النص.
*/
function sanitizeHtml(html){
  let s = String(html || '');
  s = s.replace(/<!--[\s\S]*?-->/g, '');
  /*
    ★ «/» فاصلُ سمات عند المتصفح: <svg/onload=…> يُقرأ <svg onload=…>،
    بينما نمطنا القديم لا يرى سمةً إلا بعد فراغ فيتركه كما هو (تدقيق M-05).
    نحوّل الشرطة بعد اسم الوسم إلى فراغ قبل أي فحص، فيرى النمطُ ما يراه المتصفح.
  */
  s = s.replace(/<([a-zA-Z][a-zA-Z0-9]*)\//g, '<$1 ');
  s = s.replace(/<(script|style|iframe|object|embed|link|meta)[\s\S]*?(<\/\1>|\/>|>)/gi, '');
  s = s.replace(/<\/?([a-zA-Z][a-zA-Z0-9]*)([^>]*)>/g, (m, tag) => {
    const t = tag.toLowerCase();
    if (ALLOWED_TAGS.indexOf(t) === -1) return '';
    const close = m.indexOf('</') === 0;
    // السمات كلها تُنزع — لا صنف ولا نمط ولا حدث
    return close ? '</' + t + '>' : '<' + t + '>';
  });
  /* ما بقي من «<» ليس وسمًا نظيفًا من قائمتنا — فهو نصٌّ يُهرَّب لا يُفسَّر */
  const clean = new RegExp('<(?!/?(?:' + ALLOWED_TAGS.join('|') + ')>)', 'g');
  s = s.replace(clean, '&lt;');
  return s.trim();
}

/*
  فحص المخرج كاملًا. يرمي بخطأ يسمّي العلة — «فشل التحقق» وحدها لا تدلّ
  على فعل. items: أسئلة البنك من القاعدة [{id, q, options}].
*/
function validateAnalysis(out, items){
  if (!out || typeof out !== 'object') throw new Error('ردّ التحليل ليس كائنًا');

  const topics = Array.isArray(out.topics) ? out.topics : [];
  if (!topics.length) throw new Error('التحليل بلا محاور');
  const keys = {};
  topics.forEach(t => {
    if (!t || !t.key || !t.name) throw new Error('محور بلا مفتاح أو اسم');
    if (keys[t.key]) throw new Error('مفتاح محور مكرر: ' + t.key);
    keys[t.key] = true;
  });

  /*
    ★ كل سؤال في محور، ولا محور شبح.
    سؤال بلا محور يختفي من تبويب البنك المُقسَّم، ومحور بلا أسئلة يعرض
    عدّادًا كاذبًا. العدّ هنا لا في البرومبت — البرومبت قد يَعِد ولا يفي.
  */
  const assign = out.assign || {};
  const missing = [], badKey = [];
  items.forEach(q => {
    const k = assign[q.id];
    if (!k) missing.push(q.id);
    else if (!keys[k]) badKey.push(q.id + '←' + k);
  });
  if (missing.length)
    throw new Error('أسئلة بلا محور (' + missing.length + '): ' + missing.slice(0,5).join('، '));
  if (badKey.length)
    throw new Error('أسئلة تشير لمحور غير معرّف: ' + badKey.slice(0,5).join('، '));

  const counts = {};
  items.forEach(q => { counts[assign[q.id]] = (counts[assign[q.id]] || 0) + 1; });

  const overview = sanitizeHtml(out.overview);
  const memorize = sanitizeHtml(out.memorize);
  const mistakes = sanitizeHtml(out.mistakes);
  if (overview.replace(/<[^>]+>/g,'').trim().length < 80)
    throw new Error('«عن المادة» أقصر من أن تكون تحليلًا');
  if (memorize.replace(/<[^>]+>/g,'').trim().length < 80)
    throw new Error('«طريقة الحفظ» أقصر من أن تكون تحليلًا');

  return {
    name_en: String(out.name_en || '').slice(0, 120),
    overview, memorize, mistakes,
    topics: topics.map(t => ({ key: String(t.key).slice(0,24), name: String(t.name).slice(0,120) })),
    assign, counts,
    notes: String(out.notes || '').slice(0, 4000)
  };
}

/* حمولة الذكاء من أسئلة القاعدة — الأسئلة كما هي، بلا شروح تُلوّث التحليل */
function buildUserPayload(subjectName, items){
  return JSON.stringify({
    subject_name: subjectName,
    questions: items.map(q => ({
      id: q.id, text: q.q, options: q.options, answer: q.answer
    }))
  });
}

module.exports = { SYS_ANALYST, sysFor, sanitizeHtml, validateAnalysis, buildUserPayload };
